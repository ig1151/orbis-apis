router.post('/batch', async (req: Request, res: Response) => {
  const { domains, options } = req.body;
  if (!domains || !Array.isArray(domains)) return res.status(400).json({ error: 'domains array is required', code: 'MISSING_INPUT', retryable: false });
  try {
    const raw = await callClaude(`You are an expert Domain Availability API engine performing batch availability check.\nDomains: ${JSON.stringify(domains)}\nOptions: ${JSON.stringify(options || {})}\nReturn ONLY valid JSON with keys: success, request_id, data (results array each with domain/available/tld/price_usd, total_checked, available_count), confidence, provenance, cache, recommended_next_api, recommended_actions_priority_order, execution_metadata. No markdown.`);
    res.json(parseJSON(raw));
  } catch (e: any) { res.status(500).json({ error: e.message, code: 'UPSTREAM_ERROR', retryable: true }); }
});

router.post('/execution-gate', (_req: Request, res: Response) => {
  const { input, objective } = _req.body;
  if (!input) return res.status(400).json({ error: 'input is required', code: 'MISSING_INPUT', retryable: false });
  res.json({ success: true, request_id: rid(), execution_ready: true, input, objective: objective || 'check', next_api: 'domain-availability', next_endpoint: '/check', blocking_flags: [], confidence: { score: 0.98, reason: 'Input valid', per_section: { execution_ready: 0.98 } }, provenance: { provider: 'system', retrieved_at: new Date().toISOString(), source_type: 'api_call' }, recommended_next_api: [{ api: 'domain-availability', endpoint: '/check', reason: 'Check domain availability' }], recommended_actions_priority_order: [{ priority: 'high', action: 'Call /check', reason: 'Single-request availability check' }], execution_metadata: { latency_ms: 1, model: 'system', automation_safe: true } });
});

